-- TCG Deseur 161: draft migration for the actual Floot/PostgreSQL project.
-- NOT executed by GitHub Pages and NOT automatically run on production.
-- Preserve existing 49-card tables and every user's historical inventory.
-- Review real Floot schema, authorization roles and transaction before applying.

BEGIN;

CREATE TABLE IF NOT EXISTS tcg_cards_161 (
  id text PRIMARY KEY,
  reference text NOT NULL UNIQUE,
  name text NOT NULL,
  rarity text NOT NULL CHECK (rarity IN
    ('commune','rare','epique','legendaire','hors_serie','secrete')),
  image_path text,
  normal_booster boolean NOT NULL DEFAULT TRUE,
  ordinal integer NOT NULL UNIQUE CHECK(ordinal BETWEEN 1 AND 161),
  CHECK ((id = 'td_chevelu' AND rarity = 'secrete' AND normal_booster = FALSE)
    OR (id <> 'td_chevelu' AND rarity <> 'secrete' AND normal_booster = TRUE))
);

-- Keep legacy-49 untouched rather than guessing mappings from historical card
-- names to the new photographs. New v2 inventory is independent.
CREATE TABLE IF NOT EXISTS tcg_inventory_161 (
  user_id text NOT NULL,
  card_id text NOT NULL REFERENCES tcg_cards_161(id),
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  PRIMARY KEY (user_id,card_id)
);
CREATE INDEX IF NOT EXISTS tcg_inventory_161_user_idx
  ON tcg_inventory_161(user_id);

CREATE TABLE IF NOT EXISTS tcg_secret_pack_claims_161 (
  user_id text PRIMARY KEY,
  claimed_at timestamptz NOT NULL DEFAULT now(),
  card_id text NOT NULL DEFAULT 'td_chevelu' CHECK (card_id = 'td_chevelu')
);

-- A separate history prevents the current 49-card history from breaking.
CREATE TABLE IF NOT EXISTS tcg_pack_history_161 (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL,
  opened_at timestamptz NOT NULL DEFAULT now(),
  kind text NOT NULL CHECK(kind IN ('normal','secret')),
  drawn jsonb NOT NULL CHECK (jsonb_typeof(drawn) = 'array'),
  CHECK (kind != 'secret' OR drawn = '["td_chevelu"]'::jsonb)
);
CREATE INDEX IF NOT EXISTS tcg_pack_history_161_user_date_idx
  ON tcg_pack_history_161(user_id,opened_at DESC,id DESC);

COMMIT;

